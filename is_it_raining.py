"""
Assignment:
Write a program that has a Boolean variable that represents whether or not it is raining outside. Your program should print...

>> I'm going to dance in the rain! 
if it is raining, and 

>> I'm going to dance in the sun! 
if it is not raining.
"""
is_raining = True # Sets the value to True.

if is_raining:
    print("I'm going to dance in the rain!") # If it is raining, it'll prompt the computer to output the following line. 
else:
    print("I'm going to dance in the sun!") # Otherwise, if it is not raining, it'll prompt the computer to output the following line.
