"""
Assignment:
Make variables to represent the length and width of a rectangle, called length and width, respectively. You should set length to 10 and width to 5.

Then, write some mathematical expressions to compute the area and perimeter of the rectangle and save these values inside variables named area and perimeter.

Use print statements to display the area and perimeter of the rectangle.
"""
#Sets values
length = 10
width = 5

# Area of a Rectangle: A = wl
print("Area = Width * Length")
area = width * length #Sets equation
print("Area =", area) # Print results

# Perimeter of a Rectangle: P = 2(l + w)
print("Perimeter = 2(length + width)")
perimeter = 2 * (length + width) #Sets equation
print("Perimeter =", perimeter) # Print results
